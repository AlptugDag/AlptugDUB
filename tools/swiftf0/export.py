"""Converts SwiftF0's model.onnx (MIT, github.com/lars76/swift-f0) into a C++ header.

    python export.py model.onnx ../../src/dsp/SwiftF0Model.h

The spectrogram windows, the three log-frequency filterbanks (stored sparsely) and every
convolution are written as float arrays, so the plugin runs the network without ONNX Runtime.
"""
import sys

import numpy as np
import onnx
import onnxruntime as ort
from onnx import helper, numpy_helper, shape_inference

model = onnx.load(sys.argv[1])
init = {t.name: numpy_helper.to_array(t) for t in model.graph.initializer}

# The filterbanks are built inside the graph (ScatterElements); evaluate it once to read them.
inferred = shape_inference.infer_shapes(model)
types = {v.name: v.type.tensor_type.elem_type for v in list(inferred.graph.value_info) + list(inferred.graph.output)}
probe = onnx.load(sys.argv[1])
del probe.graph.output[:]
for name in ("v127", "v245", "v346"):
    probe.graph.output.append(helper.make_tensor_value_info(name, types[name], None))
session = ort.InferenceSession(probe.SerializeToString())
fb1024, fb2048, fb512 = session.run(
    None, {"audio": np.zeros((1, 16000), np.float32), "fmin": np.array(46.875, np.float32), "fmax": np.array(2093.75, np.float32)})

convs = [  # name, weight, bias (in network order)
    ("c0", "v353", "v354"), ("c1", "v357", "v358"), ("c2", "v361", "v362"), ("c3", "v366", "v367"),
    ("c4", "v370", "v371"), ("c5", "v375", "v376"), ("c6", "v379", "v380"), ("c7", "v384", "v385"),
    ("c8", "v388", "v389"), ("c9", "v393", "v394"), ("c10", "v397", "v398"), ("c11", "v402", "v403"),
    ("c12", "v406", "v407"), ("c13", "v413", "v414"), ("c14", "v417", "v418"), ("head", "v425", "v426"),
    ("conf0", "v430", "v431"), ("conf1", "v434", "v435")]


def lit(v, digits=9):
    text = f"{float(v):.{digits}g}"
    return (text if any(c in text for c in ".e") else text + ".0") + "f"


def arr(name, values):
    flat = ", ".join(lit(v) for v in np.asarray(values, np.float32).ravel())
    return f"inline constexpr float {name}[] = {{{flat}}};\n"


def iarr(name, values):
    return f"inline constexpr int {name}[] = {{{', '.join(str(int(v)) for v in values)}}};\n"


out = ["// Generated by tools/swiftf0/export.py from SwiftF0 (MIT License, Copyright (c) Lars Nieradzik).\n",
       "// Do not edit by hand.\n#pragma once\n\nnamespace adub::swiftf0 {\n\n"]
out.append(arr("window512", init["v262"]) + arr("window1024", init["v41"]) + arr("window2048", init["v161"]))
for name, fb in (("fb512", fb512), ("fb1024", fb1024), ("fb2048", fb2048)):
    starts, counts, weights = [], [], []
    for band in range(fb.shape[1]):
        nz = np.nonzero(fb[:, band])[0]
        lo, hi = int(nz.min()), int(nz.max()) + 1
        starts.append(lo)
        counts.append(hi - lo)
        weights.extend(fb[lo:hi, band])
    out.append(iarr(name + "Start", starts) + iarr(name + "Count", counts) + arr(name + "Weights", weights))
for name, w, b in convs:
    out.append(arr(name + "W", init[w]) + arr(name + "B", init[b]))
out.append("inline constexpr float logHz[] = {" + ", ".join(lit(v, 12) for v in init["v455"]) + "};\n")
out.append("inline constexpr float binHz[] = {" + ", ".join(lit(v) for v in init["v438"]) + "};\n")
out.append("\n} // namespace adub::swiftf0\n")
open(sys.argv[2], "w").write("".join(out))
print("wrote", sys.argv[2])
